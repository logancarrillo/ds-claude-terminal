#include "render.h"

#include <nds.h>

#include "font.h"
#include "lang.h"
#include "privacy.h"
#include "ui_font.h"

#define SCREEN_W 256
#define SCREEN_H 192

// The terminal's cell size and origin follow the grid geometry.  The sub
// screen's 6x8 UI font (font.h) is fixed and unaffected.
#define TERM_CELL_W (SCREEN_W / PROTO_COLS)
#define TERM_CELL_H (SCREEN_H / PROTO_ROWS)
#define ORIGIN_X ((SCREEN_W - PROTO_COLS * TERM_CELL_W) / 2)
#define ORIGIN_Y ((SCREEN_H - PROTO_ROWS * TERM_CELL_H) / 2)

// The terminal font must be the cell size exactly: 42x24 is 6x8, 51x27 is
// 5x7, 64x32 is 4x6.  All three are generated by tools/genfont.py from the
// same Spleen source, so the zoom level never changes letterforms.  The term
// headers define TERM_FONT_W/H and their own tables so the sub screen's 6x8
// font.h (FONT_W/H, font6x8) can be included alongside them.
#if TERM_CELL_W == 6
#include "font.h"
#define TERM_TABLE font6x8
#define TERM_EXT   font6x8_ext
#define TERM_FONT_W FONT_W
#define TERM_FONT_H FONT_H
#elif TERM_CELL_W == 5
#include "font5x7.h"
#define TERM_TABLE font_term
#define TERM_EXT   font_term_ext
#elif TERM_CELL_W == 4
#include "font4x6.h"
#define TERM_TABLE font_term
#define TERM_EXT   font_term_ext
#else
#error "no terminal font for this grid geometry"
#endif

typedef char term_font_must_match_cell[
    (TERM_FONT_W == TERM_CELL_W && TERM_FONT_H == TERM_CELL_H) ? 1 : -1];

// The terminal glyph loop, defined below with the other painters but used by
// the overlays first.
static void render_glyph_term(uint16_t *target, int stride, int px, int py,
                              uint8_t glyph, uint16_t fgc, uint16_t bgc);

static u16 *fb;
// The background the terminal lives on, and where the shake currently
// has it.  Both are needed by render_set_shake(), which is the only thing that
// ever moves the terminal off its own grid -- and which always puts it back.
static int bg_id;
static int shake_y;

static void render_glyph_term(uint16_t *target, int stride, int px, int py,
                              uint8_t glyph, uint16_t fgc, uint16_t bgc);

// The terminal caret, as grid coordinates. Kept here because the framebuffer is
// the only state that can tell where the caret's pixels actually are: a scroll
// moves them along with everything else, and the CURSOR message that follows
// needs to know the vacated position to repaint it (render_scroll shifts these
// in step with the pixels, so they never drift).
static int cur_row = -1;
static int cur_col = -1;
static int cur_visible = 0;
static int overlay_active = 0;

// RGB15. Kept slightly below full brightness: the DS Phat/Lite screens are dim
// and pure 31s bloom badly against black.
// Not const: PAL_ORANGE is the accent, which Settings' THEME can change.
static u16 palette[10] = {
    [PAL_DEFAULT] = ARGB16(1, 27, 27, 27),
    [PAL_BLACK]   = ARGB16(1,  0,  0,  0),
    [PAL_RED]     = ARGB16(1, 26,  5,  5),
    [PAL_GREEN]   = ARGB16(1,  6, 26,  6),
    [PAL_YELLOW]  = ARGB16(1, 27, 24,  6),
    [PAL_BLUE]    = ARGB16(1,  8, 12, 29),
    [PAL_MAGENTA] = ARGB16(1, 26,  8, 26),
    [PAL_CYAN]    = ARGB16(1,  6, 25, 26),
    [PAL_WHITE]   = ARGB16(1, 31, 31, 31),
    [PAL_ORANGE]  = ARGB16(1, 27, 15, 11),
};

// Background "default" is the terminal background, not the foreground colour,
// so it cannot share the table above.
#define BG_DEFAULT ARGB16(1, 0, 0, 0)

static inline u16 fg_colour(uint8_t idx, int bold)
{
    const u16 c = palette[idx <= PAL_ORANGE ? idx : PAL_DEFAULT];
    if (!bold) return c;
    // Brighten rather than switching to a second palette: bold is used heavily
    // by Claude Code's TUI and a whole extra colour set is not worth the VRAM.
    const int r = ((c >> 0) & 31), g = ((c >> 5) & 31), b = ((c >> 10) & 31);
    const int br = r + (31 - r) / 2, bg = g + (31 - g) / 2, bb = b + (31 - b) / 2;
    return ARGB16(1, br, bg, bb);
}

static inline u16 bg_colour(uint8_t idx)
{
    if (idx == PAL_DEFAULT) return BG_DEFAULT;
    return palette[idx <= PAL_ORANGE ? idx : PAL_BLACK];
}

uint16_t render_palette_rgb(uint8_t idx)
{
    return palette[idx <= PAL_ORANGE ? idx : PAL_DEFAULT];
}

int render_set_accent(uint16_t rgb)
{
    if (palette[PAL_ORANGE] == rgb) return 0;
    palette[PAL_ORANGE] = rgb;
    return 1;
}

void render_init(void)
{
    // consoleDemoInit() powers and configures the sub engine only. Without
    // powering the main engine explicitly the top screen stays blank white
    // whatever is written to VRAM, which looks exactly like a renderer that
    // never ran.
    powerOn(POWER_ALL_2D);
    lcdMainOnTop();

    // MODE_5's 16-bit BG3 gives the terminal the same 256px-wide pixel surface
    // as the old direct LCD framebuffer, but leaves main sprites enabled.  The
    // background is 256x256 because that is the DS bitmap mode's native size;
    // the renderer still touches only the visible 256x192 top portion.
    videoSetMode(MODE_5_2D);
    vramSetBankA(VRAM_A_MAIN_BG);
    bg_id = bgInit(3, BgType_Bmp16, BgSize_B16_256x256, 0, 0);
    fb = (u16 *)bgGetGfxPtr(bg_id);
    // Clear all 256 rows, not only the 192 the terminal uses.  The extra
    // sixty-four are uninitialised VRAM, and the moment the background is
    // scrolled -- which is exactly what the impact shake does -- they become
    // the strip at the edge of the screen.  Once, at boot, so the shake never
    // has to think about it.
    for (int i = 0; i < SCREEN_W * 256; i++) fb[i] = BG_DEFAULT;
    render_clear();
}

void render_set_shake(int offset_y)
{
    // Vertical only: this background is exactly as wide as the screen, so a
    // horizontal scroll wraps the rightmost column of terminal text around to
    // the left.  Bounded here as well as at the source, because the whole
    // terminal moving is not the kind of thing to leave to one caller getting
    // its arithmetic right.
    int dy = offset_y;
    if (dy > (int)RENDER_SHAKE_MAX) dy = (int)RENDER_SHAKE_MAX;
    if (dy < -(int)RENDER_SHAKE_MAX) dy = -(int)RENDER_SHAKE_MAX;
    if (dy == shake_y) return;
    shake_y = dy;
    // The scroll is the source origin, so a positive offset moves the picture
    // up.  Either sign shakes; keeping the convention written down is what
    // stops the next change from inverting it by accident.
    bgSetScroll(bg_id, 0, dy);
    bgUpdate();
}

void render_clear(void)
{
    for (int i = 0; i < SCREEN_W * SCREEN_H; i++) fb[i] = BG_DEFAULT;
}

void render_overlay_text(const char *title, const char *body, const char *hint)
{
    overlay_active = 1;
    render_clear();
    // HIDE ADDRESSES (privacy.h): masked here, once, for every overlay.
    title = privacy_text(title);
    body = privacy_text(body);
    hint = privacy_text(hint);
    const char *p = title;
    int row = 0, col = 0;
    while (*p && col < PROTO_COLS) {
        render_glyph_term(fb, SCREEN_W, ORIGIN_X + col++ * TERM_CELL_W,
                          ORIGIN_Y + row * TERM_CELL_H,
                          (uint8_t)*p++, ARGB16(1, 31, 20, 10), BG_DEFAULT);
    }
    row = 2; col = 0; p = body;
    while (*p && row < PROTO_ROWS - 2) {
        if (*p == '\n' || col == PROTO_COLS) { row++; col = 0; if (*p == '\n') p++; continue; }
        render_glyph_term(fb, SCREEN_W, ORIGIN_X + col++ * TERM_CELL_W,
                          ORIGIN_Y + row * TERM_CELL_H,
                          (uint8_t)*p++, ARGB16(1, 28, 27, 24), BG_DEFAULT);
    }
    p = hint;
    row = PROTO_ROWS - 1; col = 0;
    while (*p && col < PROTO_COLS) {
        render_glyph_term(fb, SCREEN_W, ORIGIN_X + col++ * TERM_CELL_W,
                          ORIGIN_Y + row * TERM_CELL_H,
                          (uint8_t)*p++, ARGB16(1, 18, 18, 18), BG_DEFAULT);
    }
}

// Paint one clipped overlay text row. Unlike render_glyph_into()'s public
// primitive, this helper owns the bounds: callers supply labels from local
// files or the wire, so no byte of an overlong or malformed label may walk off
// the 256x192 framebuffer. It paints every cell's background, which is what
// makes the selected-row fill a real highlight rather than orange text that
// disappears among terminal colours.
static void overlay_list_row(int row, const char *text, u16 fg, u16 bg)
{
    if (row < 0 || row >= PROTO_ROWS) return;
    if (!text) text = "";

    // Do not index text[col]: after a short label reaches its terminator, that
    // form continues reading whatever happens to follow the string. Holding at
    // the terminator makes all remaining cells spaces without looking past the
    // caller's NUL-terminated storage.
    const char *p = privacy_text(text);
    for (int col = 0; col < PROTO_COLS; col++) {
        const uint8_t glyph = *p ? (uint8_t)*p++ : (uint8_t)' ';
        render_glyph_term(fb, SCREEN_W, ORIGIN_X + col * TERM_CELL_W,
                          ORIGIN_Y + row * TERM_CELL_H,
                          glyph, fg, bg);
    }
}

void render_overlay_list(const char *title, const char * const *rows,
                         int count, int selected, int focused,
                         const char *hint)
{
    // The list overlay has the same ownership contract as render_overlay_text:
    // terminal diffs update the model while this is on-screen, and
    // render_overlay_close() restores it in one grid redraw.
    overlay_active = 1;
    render_clear();

    // Keep title and hint behaviour exactly parallel to the existing text
    // overlay, but make NULL inputs harmless so protocol/reconnect paths can
    // repaint defensively.
    overlay_list_row(0, title, ARGB16(1, 31, 20, 10), BG_DEFAULT);
    overlay_list_row(PROTO_ROWS - 1, hint, ARGB16(1, 18, 18, 18), BG_DEFAULT);

    // Rows 1 and 22 are intentionally blank: they separate the title/list and
    // list/hint on the small screen.  That leaves twenty list rows, enough for
    // all current snippets and sessions while keeping a selection highlight
    // from touching either chrome line.
    const int first = 2;
    const int visible = PROTO_ROWS - first - 2;
    if (!rows || count <= 0) return;

    // A giant count from an unchecked caller must not overflow a loop index or
    // cause reads beyond the labels the caller says it owns.  The list has no
    // scrolling state at this layer; it renders only the safely visible prefix.
    if (count > visible) count = visible;
    for (int i = 0; i < count; i++) {
        const int is_selected = focused && i == selected;
        overlay_list_row(first + i, rows[i],
                         is_selected ? BG_DEFAULT : ARGB16(1, 28, 27, 24),
                         is_selected ? render_palette_rgb(PAL_ORANGE) : BG_DEFAULT);
    }
}

// A whole grid the *client* built, painted over the terminal.
//
// The other two overlays lay out text themselves; this one takes a finished
// grid and draws it exactly as the terminal is drawn, which is the point. The
// PROJECT page is composed into an ordinary grid_t so that it is made of the
// same glyphs as everything else, and so that an extension's safe-rect search
// works on it without knowing it is not the terminal. All this needs to do is
// put those cells on the screen, and set the flag that stops the server's
// diffs from drawing over them -- the model keeps updating underneath, which
// is why handing the screen back is one call and no resync.
void render_overlay_grid(const grid_t *g)
{
    if (!g) return;
    overlay_active = 1;
    for (int r = 0; r < PROTO_ROWS; r++) {
        for (int c = 0; c < PROTO_COLS; c++) {
            // apply_caret is 0: the caret belongs to the terminal, and a block
            // cursor blinking on a status page is a cursor you would try to
            // type at.
            render_term_cell_into(fb, SCREEN_W, 0, r, c,
                                  g->cells[r * PROTO_COLS + c]);
        }
    }
}

// A boxed note over whatever overlay is up: the controls guide's pop-up
// (guide.h places it, clear of the still session's input line).  A box with
// an accent border, drawn in the UI font rather than the terminal's so every
// language's text fits it, and drawn once -- it is not terminal text, so it
// cannot scroll away or be overwritten by a diff (overlay_active is already
// set by the overlay underneath).
void render_overlay_box(int x, int y, int w, int h, const char *const *lines,
                        const uint16_t *colours, int count, int pitch)
{
    if (x < 0 || y < 0 || w < 8 || h < 8 ||
        x + w > SCREEN_W || y + h > SCREEN_H) return;
    const u16 border = palette[PAL_ORANGE];
    const u16 fill = ARGB16(1, 2, 2, 4);
    for (int yy = y; yy < y + h; yy++) {
        for (int xx = x; xx < x + w; xx++) {
            const int edge = yy < y + 2 || yy >= y + h - 2 ||
                             xx < x + 2 || xx >= x + w - 2;
            fb[yy * SCREEN_W + xx] = edge ? border : fill;
        }
    }
    const int pad = 6;
    const int right = x + w - pad;
    for (int i = 0; i < count && lines; i++) {
        const char *p = lines[i] ? privacy_text(lines[i]) : "";
        // The CJK atlas's glyphs reach one row above the line: start a row
        // lower so the first line clears the border.
        const int py = y + pad + 1 + i * pitch;
        if (py + 9 > y + h - 2) break;
        const u16 fg = colours ? colours[i] : palette[PAL_DEFAULT];
        int px = x + pad;
        while (*p) {
            const uint8_t b0 = (uint8_t)*p;
            if (b0 < 0xC0) {   // ASCII, or a raw wire glyph
                if (px + 6 > right) break;
                render_glyph_into(fb, SCREEN_W, px, py, b0, fg, fill);
                p++;
                px += 6;
                continue;
            }
            const char *q = p;
            const uint32_t cp = lang_utf8_next(&q);
            const int wide = lang_cp_is_wide(cp) ? 12 : 6;
            if (px + wide > right) break;
            px += render_unicode_into(fb, SCREEN_W, px, py, cp, fg, fill);
            p = q;
        }
    }
}

void render_overlay_close(const grid_t *g)
{
    overlay_active = 0;
    if (g) render_grid(g);
}

int render_overlay_active(void) { return overlay_active; }

void render_glyph_into(uint16_t *target, int stride, int px, int py,
                       uint8_t glyph, uint16_t fgc, uint16_t bgc)
{
    // ASCII, then the extended table (box drawing, blocks, status marks).
    // Anything else renders as '?' rather than blank, so a protocol bug is
    // visible instead of silent.
    const uint8_t *rows;
    if (glyph >= FONT_FIRST && glyph <= FONT_LAST) {
        rows = font6x8[glyph - FONT_FIRST];
    } else if (glyph >= FONT_EXT_BASE && glyph < FONT_EXT_BASE + FONT_EXT_COUNT) {
        rows = font6x8_ext[glyph - FONT_EXT_BASE];
    } else {
        rows = font6x8['?' - FONT_FIRST];
    }

    for (int y = 0; y < FONT_H; y++) {
        uint16_t *line = target + (py + y) * stride + px;
        const uint8_t bits = rows[y];
        for (int x = 0; x < FONT_W; x++) {
            line[x] = (bits & (1 << (FONT_W - 1 - x))) ? fgc : bgc;
        }
    }
}

int render_unicode_into(uint16_t *target, int stride, int px, int py,
                        uint32_t cp, uint16_t fgc, uint16_t bgc)
{
    if (cp <= 0x7E) {
        render_glyph_into(target, stride, px, py, (uint8_t)cp, fgc, bgc);
        return FONT_W;
    }
    // Accented Latin letters from the terminal font's own letter plus a mark
    // (lang.h): the atlas's versions of these are too heavy to tell apart.
    uint8_t latin[FONT_H];
    if (lang_latin_glyph(cp, font6x8, latin)) {
        if (px < 0 || py < 0 || px + FONT_W > stride || py + FONT_H > 256) {
            return FONT_W;
        }
        for (int y = 0; y < FONT_H; y++) {
            uint16_t *line = target + (py + y) * stride + px;
            for (int x = 0; x < FONT_W; x++) {
                line[x] = (latin[y] & (1 << (FONT_W - 1 - x))) ? fgc : bgc;
            }
        }
        return FONT_W;
    }
    const ui_glyph_t *g = ui_font_lookup(cp);
    if (!g) {
        render_glyph_into(target, stride, px, py, (uint8_t)'?', fgc, bgc);
        return FONT_W;
    }
    const int w = (int)g->width;
    if (px < 0 || py < 0 || px + w > stride || py + FONT_H > 256) return w;
    // A CJK glyph is 10 rows (Fusion Pixel 10px) on an 8-row text line.
    // Drawing only the line's 8 cut the top and bottom off every character
    // -- legible in the font, unreadable on the DS. It is centred on the
    // line instead: one row above, one below, and those two rows paint the
    // glyph's own pixels only, never background, so a neighbouring line
    // drawn before or after this one keeps everything it drew.
    const int h = (int)g->height < UI_FONT_H ? (int)g->height : UI_FONT_H;
    const int y0 = py - (h - FONT_H) / 2;
    for (int y = 0; y < h; y++) {
        const int sy = y0 + y;
        if (sy < 0 || sy >= 256) continue;
        const int inside = sy >= py && sy < py + FONT_H;
        uint16_t *line = target + sy * stride + px;
        const uint16_t bits = g->rows[y];
        for (int x = 0; x < w; x++) {
            if (bits & (1u << (w - 1 - x))) line[x] = fgc;
            else if (inside)                 line[x] = bgc;
        }
    }
    return w;
}

// The terminal's own glyph loop at the grid cell size, using the geometry's
// font table (TERM_TABLE/TERM_EXT, whose TERM_FONT_W/H the compile-time check
// above pins to the cell size).  Identical semantics to render_glyph_into.
static void render_glyph_term(uint16_t *target, int stride, int px, int py,
                              uint8_t glyph, uint16_t fgc, uint16_t bgc)
{
    const uint8_t *rows;
    if (glyph >= FONT_FIRST && glyph <= FONT_LAST) {
        rows = TERM_TABLE[glyph - FONT_FIRST];
    } else if (glyph >= FONT_EXT_BASE && glyph < FONT_EXT_BASE + FONT_EXT_COUNT) {
        rows = TERM_EXT[glyph - FONT_EXT_BASE];
    } else {
        rows = TERM_TABLE['?' - FONT_FIRST];
    }

    for (int y = 0; y < TERM_FONT_H; y++) {
        uint16_t *line = target + (py + y) * stride + px;
        const uint8_t bits = rows[y];
        for (int x = 0; x < TERM_FONT_W; x++) {
            line[x] = (bits & (1 << (TERM_FONT_W - 1 - x))) ? fgc : bgc;
        }
    }
}

static void cell_into(uint16_t *target, int stride, int apply_caret,
                      int row, int col, cell_t c, int term)
{
    if (row < 0 || row >= PROTO_ROWS || col < 0 || col >= PROTO_COLS) return;

    u16 fgc = fg_colour(CELL_FG(c), c.flags & CELL_FLAG_BOLD);
    u16 bgc = bg_colour(CELL_BG(c));
    if (c.flags & CELL_FLAG_REVERSE) {
        const u16 t = fgc; fgc = bgc; bgc = t;
    }
    // The caret is drawn as a second inversion, so it is a solid block over
    // any content -- including content that is itself reverse-video, where it
    // reads as the un-inverted text, matching a block caret over a selection.
    if (apply_caret && cur_visible && row == cur_row && col == cur_col) {
        const u16 t = fgc; fgc = bgc; bgc = t;
    }

    if (term) {
        render_glyph_term(target, stride,
                          ORIGIN_X + col * TERM_CELL_W,
                          ORIGIN_Y + row * TERM_CELL_H,
                          c.glyph, fgc, bgc);
    } else {
        // The sub screen's fixed 6x8 layout; its origin is its own.
        render_glyph_into(target, stride, col * 6, row * 8, c.glyph, fgc, bgc);
    }
}

void render_cell_into(uint16_t *target, int stride, int apply_caret,
                      int row, int col, cell_t c)
{
    cell_into(target, stride, apply_caret, row, col, c, 0);
}

void render_term_cell_into(uint16_t *target, int stride, int apply_caret,
                           int row, int col, cell_t c)
{
    cell_into(target, stride, apply_caret, row, col, c, 1);
}

void render_cell(int row, int col, cell_t c)
{
    if (overlay_active) return;
    render_term_cell_into(fb, SCREEN_W, 1, row, col, c);
}

void render_grid(const grid_t *g)
{
    if (overlay_active) return;
    for (int r = 0; r < PROTO_ROWS; r++) {
        for (int c = 0; c < PROTO_COLS; c++) {
            render_cell(r, c, g->cells[r * PROTO_COLS + c]);
        }
    }
}

void render_scroll(int lines)
{
    if (lines < 1 || lines >= PROTO_ROWS) return;

    if (!overlay_active) {
        const int shift = lines * TERM_CELL_H;         // pixel rows

        // Move the grid region up by `shift`, leaving the blank margins
        // alone: a u16 loop rather than memmove, because VRAM does not
        // tolerate byte-granular writes, and memmove is free to use them.
        for (int y = ORIGIN_Y; y < SCREEN_H - shift; y++) {
            uint16_t *dst_row = fb + y * SCREEN_W;
            const uint16_t *src_row = fb + (y + shift) * SCREEN_W;
            for (int x = 0; x < SCREEN_W; x++) dst_row[x] = src_row[x];
        }
        for (int y = SCREEN_H - shift; y < SCREEN_H; y++) {
            uint16_t *row = fb + y * SCREEN_W;
            for (int x = 0; x < SCREEN_W; x++) row[x] = BG_DEFAULT;
        }
    }

    // The caret's pixels scrolled up with everything else. Track that, or the
    // CURSOR message that follows repaints the wrong cell and leaves a trail.
    // A caret that scrolled off the top is gone: hide it rather than let it
    // claim a cell it no longer occupies.
    if (cur_visible) {
        cur_row -= lines;
        if (cur_row < 0) {
            cur_row = 0;
            cur_visible = 0;
        }
    }
}

void render_cursor_set(const grid_t *g, int row, int col, int visible)
{
    if (row < 0 || row >= PROTO_ROWS || col < 0 || col >= PROTO_COLS) return;

    const int old_row = cur_row, old_col = cur_col, old_vis = cur_visible;
    cur_row = row;
    cur_col = col;
    cur_visible = visible ? 1 : 0;
    if (overlay_active) return;

    // Repaint the cell the caret just left, unless it is the same cell the
    // caret now occupies -- that one is redrawn inverted below, and repainting
    // it first would clear the very inversion being drawn. The caret hiding in
    // place is the one case that differs: it leaves its cell, so repaint it.
    if (old_vis && g && (old_row != row || old_col != col || !cur_visible)) {
        render_cell(old_row, old_col, g->cells[(size_t)old_row * PROTO_COLS + old_col]);
    }
    if (cur_visible && g) {
        render_cell(row, col, g->cells[(size_t)row * PROTO_COLS + col]);
    }
}
